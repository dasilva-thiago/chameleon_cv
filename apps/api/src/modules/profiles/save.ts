import type { OnMissingMode, ProfileDocument } from '@chameleon/contracts';
import { HttpError } from '../../http/errors';
import { emptyDocument, enforceArchivedNever, unknownIds } from './doc';
import { requireValidDocument, validationError } from './errors';
import type { ProfileScope } from './scope';
import { saveResultDto, stateResponse } from './views';

/**
 * Shared write path. MUST run inside `scope.exclusive` (read-modify-write over the whole document):
 *   1. `base` = stored document (or an empty one when the owner has no profile yet);
 *   2. the caller builds `next` from `base` (a pure operation of `doc.ts`);
 *   3. ids that the stored profile does not know are refused (records are created by OMITTING the id);
 *   4. the contract validates the whole document (integrity, references, field_states);
 *   5. the store saves (see `onMissing` below) and the result is reloaded.
 */
export async function loadBase(scope: ProfileScope): Promise<{
  base: ProfileDocument;
  exists: boolean;
}> {
  const loaded = await scope.store.loadProfileDocument();
  return { base: loaded?.document ?? emptyDocument(), exists: loaded !== null };
}

export async function commit(
  scope: ProfileScope,
  base: ProfileDocument,
  next: ProfileDocument,
  options: {
    /**
     * What the store does with stored records the document omits. Omitted = `archive`, which is the right
     * mode when `next` was derived from the COMPLETE stored document (every per-record operation): nothing is
     * missing, and unlike `keep` it lets the store drop link rows removed from `supports`/`evidence_ids`.
     * Whole-document and section saves pass the client's explicit choice (default `keep`).
     */
    onMissing?: OnMissingMode;
    createRevision?: boolean;
    /** Ids generated by the server for this write (allowed although the stored profile does not have them). */
    generatedIds?: ReadonlySet<string>;
  } = {},
) {
  const unknown = unknownIds(next, base, options.generatedIds);
  if (unknown.length > 0) {
    throw validationError(
      unknown.slice(0, 20).map(() => ({
        path: 'document',
        message: 'Id de registro desconhecido neste perfil: omita o id para criar um registro.',
      })),
    );
  }
  const archived = enforceArchivedNever(next);
  if (archived.violations.length > 0) {
    throw validationError(
      archived.violations.slice(0, 20).map(() => ({
        path: 'meta.resume_use',
        message:
          'Um registro arquivado nao pode ser usado em curriculo (resume_use deve ser never).',
      })),
    );
  }
  const valid = requireValidDocument(archived.document);
  const save = await scope.store.saveProfileDocument(valid, {
    onMissing: options.onMissing ?? 'archive',
    ...(options.createRevision ? { revision: 'manual_save' as const } : {}),
  });
  const loaded = await scope.store.loadProfileDocument();
  if (!loaded) throw new HttpError(500, 'INTERNAL_ERROR', 'Erro interno.');
  return {
    save: saveResultDto(save),
    loaded,
    state: stateResponse(loaded),
    profileId: save.profileId,
  };
}
